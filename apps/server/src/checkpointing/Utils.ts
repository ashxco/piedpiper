import { Encoding } from "effect";
import { CheckpointRef, ProjectId, type ThreadId } from "@piedpiper/contracts";

export const CHECKPOINT_REFS_PREFIX = "refs/piedpiper/checkpoints";

export function checkpointRefForThreadTurn(threadId: ThreadId, turnCount: number): CheckpointRef {
  return CheckpointRef.makeUnsafe(
    `${CHECKPOINT_REFS_PREFIX}/${Encoding.encodeBase64Url(threadId)}/turn/${turnCount}`,
  );
}

export function resolveThreadWorkspaceCwd(input: {
  readonly thread: {
    readonly projectId: ProjectId;
    readonly worktreePath: string | null;
  };
  readonly projects: ReadonlyMap<ProjectId, { readonly workspaceRoot: string }>;
}): string | undefined {
  const worktreeCwd = input.thread.worktreePath ?? undefined;
  if (worktreeCwd) {
    return worktreeCwd;
  }

  return input.projects.get(input.thread.projectId)?.workspaceRoot;
}
